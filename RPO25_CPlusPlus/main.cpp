#include <iostream>
#include <string>
#include <vector> // коллекция вектора
#include <deque> // коллекция двусторонней очереди
#include <list> // коллекция двухсвязного списка
#include <forward_list> // коллекция односвязного списка
#include <set> // коллекция множества
#include <map> // коллекция словаря

int main()
{
    setlocale(LC_ALL, "RU");

    // Коллекции - это контейнеры, содержащие наборы объектов и позволяющие управлять доступом к этим элементам. В языках программирования обычно есть два типа коллекций: ассоциативные и последовательные.
    // Последовательный контейнер хранит элементы последовательно, при этом элементы располагаются друг рядом с другом. Их порядок может меняться в зависимости от конкретного контейнера.
    // Виды:
    // 1. Массив - произвольный доступ, добавлять удалять элементы нельзя.
    int array[5] = { 1, 2, 3, 4, 5 };
    // 2. Вектор - переменный размер, произвольный доступ, добавление и удаление из любого места.
    // vector - класс
    // <тип_данных> - параметр в виде типа данных, по которому класс строит коллекцию
    std::vector<int> vectorArray = { 1, 2, 3, 4, 5 };
    // 3. Двусторонняя очередь - произвольный доступ, удаление и добавление в конце и начале коллекци
    std::deque<int> dq = { 5, 10 };
    // Среди преимуществ можно выделить быстроту работы (O1), а также то, что данная очередь не хранит все элементы в одном непрерывном блоке памяти из-за чего не происходит копирование всего массива.
    // 4. Двухсвязный список - только последовательный двухнаправленный доступ к элементам, удаление и добавление в начале и в конце контейнера.
    std::list<int> listArray = { 1, 2, 3, 4, 5 };
    // 5. Односвязный список - однонаправленный последовательный доступ к элементам, удаление и добавление в начале и в конце контейнера.
    std::forward_list<int> frwdListArray = { 1, 2, 3 };
    // Таким образом, последовательные контейнеры применяются при необходимости перечислять элементы в каком либо направлении. В зависимости от ситуации и потребностей можно использовать тот или иной тип. Например, если нужно иметь возможность найти произвольный элемент, то применяется vector. Если нужно иметь возможность добавлять или удалять элементы в середине контейнера, то можно применять list или forward_list, что с вектором сделать сложнее. Чаще всего используется vector.

    // Ассоциативные контейнеры представляют собой такие контейнеры, где с каждым элементом ассоциирован некоторый ключ, и этот ключ применяется для доступа к элементу.
    // Виды:
    // 1. Множество - хранит только уникальные значения. Является ассоциативным, потому что сам элемент одновременно является и ключом. Внутри данного контейнера реализована структура быстрого поиска, которая ищет по ключу.
    std::set<int> setArray = { 1, 2, 3, 4, 5 };
    setArray.insert(3);
    for (int n : setArray)
    {
        std::cout << n << std::endl;
    }
    // 2. Словарь - контейнер, где каждое значение ассоциировано с определенным ключом. Ключи могут иметь только уникальное значени!
    std::map<int, std::string> dictionaryArray;
    dictionaryArray[1] = "Привет";
    dictionaryArray[2] = "От";
    dictionaryArray[3] = "РПО";
    std::cout << dictionaryArray[1] << " " << dictionaryArray[2] << " " << dictionaryArray[3] << std::endl;

    // Практика.
    // 1. Создайте структуру книги, которая содержит id, название, автора, год. Создайте основной каталог книг на основе контейнера vector. Добавьте в него минимум 5 книг.
    // 2. Создайте контейнер map, где ключом выступает id книги, а значением сама структура книги. Заполните контейнер данными из вектора.
    // 3. Создайте контейнер множества. Пройдите циклом по каталогу книг и добавьте всех авторов в это множество. Выведите содержимое на экран и убедитесь, что джубликатов нет.
    // Примечание: для удобного вывода элементов коллекций можно использовать аналог цикла foreach в С++
    for (int n : setArray) // аналог foreach в С++
    {
        std::cout << n << std::endl;
    }

}