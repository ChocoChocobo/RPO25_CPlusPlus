#include <iostream>
#include <vector>

int main()
{
    setlocale(LC_ALL, "RU");

    // Указатели и работа с типом данных void
    // Обычную переменную с таким типом данных создать невозможно, однако можно создать указатель на этот тип!!! Указателю на void можно присвоить значение указателя любого другого типа.
    void* ptrVoid;
    int value, *ptrValue;
    ptrValue = &value;
    ptrVoid = ptrValue;
    ptrValue = (int*)ptrVoid; // Для того, чтобы задать указателю указатель на тип данных void, необходимо преобразовать тип данных в соответствующий
    // Над указателями можно производить арифметические операции, а именно сложение и вычитание.
    int* ptr;
    int x = 12;
    ptr = &x;
    //std::cout << ptr << std::endl;
    //std::cout << ++ptr << std::endl;
    // При выполнении операции инкремента значение указателя на память переменной x увеличивается на 4. Происходит это из-за того, что при арифметических операциях над указателями мы имеем дело с памятью системы и тем, сколько памяти занимает конкретный тип данных. В нашем случае int занимает 4 байт.
    // Общая формула для вычисления значения указатели после операции прибавления:
    // ptr = ptr + n * размер_в_байтах_переменной_базового_типа

    // В языке С++ допускается использование указателей, указывающих на указатель.
    int** ptrUltra;
    // Переменная ptrUltra имеет тип указателя на указатель. Соответственно, чтобы получить целочисленное значение переменной, на которую указывает ptrUltra, нужно в выражении использовать **ptrUltra.
    // * также называется операцией разыменования!
    int y;
    int* ptrY;
    int** ppY; // Альтернативно можно писать ptrPY, ptrptrY, главное, чтобы название отражало суть переменной!
    y = 6;
    ptrY = &y;
    ppY = &ptrY;
    /*std::cout << y << std::endl;
    std::cout << ptrY << std::endl;
    std::cout << ppY << std::endl;
    std::cout << *ptrY << std::endl;
    std::cout << **ppY << std::endl;
    std::cout << &ptrY << std::endl;
    std::cout << &ppY << std::endl;*/

    // Динамическое выделение памяти
    // Помимо рассмотренных действий с указателями с их помощью можно также создавать переменные и выделять память динамически по ходу выполнения программы. Для этого предназначен оператор new.
    // Синтаксис: указатель = new тип_данных;
    int* ptrInt; // переменная указателя на целое
    ptrInt = new int; // выделяем память 
    *ptrInt = 3;
    //std::cout << ptrInt << std::endl;
    //std::cout << *ptrInt << std::endl;
    // Динамическую память необходимо очистить, когда она больше не нужна. Для того, чтобы память очистить, нужно применить оператор delete
    delete ptrInt;
    //std::cout << ptrInt << std::endl;
    // Удаления указателя при этом не происходит, память, адрес, который находится в указателе, объявляется свободной.
}

